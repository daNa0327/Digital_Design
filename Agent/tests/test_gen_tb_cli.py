"""scripts/gen_tb.py 명령줄: --dry-run, --check, --gate (FakeLLM과 가짜 run_tool로 외부 의존 없이)."""

from types import SimpleNamespace

import pytest

from llm import FakeLLM, LLMClient
from scripts import gen_tb
from tests.test_tb_check import DUT, GOOD_TB

XVLOG_FAIL = ("ERROR: [VRFC 10-8885] declarations are not allowed in an unnamed block [C:/x/tb.v:4]\n"
              "ERROR: [VRFC 10-8530] module 'tb_counter' is ignored due to previous errors [C:/x/tb.v:1]\n")


@pytest.fixture
def rtl(tmp_path):
    f = tmp_path / "counter.v"
    f.write_text(DUT)
    return f


def fenced(code):
    return f"```verilog\n{code}```"


def install(monkeypatch, replies, xvlog_outputs):
    """FakeLLM 응답과 xvlog 출력 순서를 정해 CLI의 외부 의존(LLM, 도구)을 가짜로 바꾼다."""
    fake = FakeLLM(replies)
    monkeypatch.setattr(gen_tb, "make_client", lambda: LLMClient(fake))
    monkeypatch.setattr(gen_tb, "load_env", lambda: {})
    outs = list(xvlog_outputs)

    def run_tool(name, args, cwd, timeout=None):
        if name == "xvlog":
            out = outs.pop(0)
            return SimpleNamespace(returncode=1 if "ERROR" in out else 0, stdout=out, duration_s=0.1, timed_out=False)
        return SimpleNamespace(returncode=0, stdout="", duration_s=0.1, timed_out=False)

    monkeypatch.setattr("core.compile_gate.run_tool", run_tool)
    return fake


def test_dry_run_writes_prompt_without_calling_llm(rtl, tmp_path, capsys):
    """--dry-run은 프롬프트 파일만 만들고 LLM을 부르지 않는다."""
    out = tmp_path / "p.txt"
    assert gen_tb.main([str(rtl), "--top", "counter", "--dry-run", "--out", str(out)]) == 0
    assert "OUTPUT CONTRACT" in out.read_text(encoding="utf-8")


def test_check_mode_exit_code_follows_static_errors(rtl, tmp_path):
    """--check: error가 없으면 종료 코드 0, 있으면 1."""
    good, bad = tmp_path / "g.v", tmp_path / "b.v"
    good.write_text(GOOD_TB)
    bad.write_text(GOOD_TB.replace("$finish;", ""))
    assert gen_tb.main([str(rtl), "--top", "counter", "--check", str(good)]) == 0
    assert gen_tb.main([str(rtl), "--top", "counter", "--check", str(bad)]) == 1


def test_gate_retries_with_feedback_and_saves_final(rtl, tmp_path, monkeypatch, capsys):
    """--gate: 첫 시도 컴파일 실패 -> 에러를 되먹여 재생성 -> 통과, 최종 TB를 저장하고 종료 코드 0."""
    fake = install(monkeypatch, [fenced(GOOD_TB), fenced(GOOD_TB)], [XVLOG_FAIL, ""])
    out = tmp_path / "tb.v"
    rc = gen_tb.main([str(rtl), "--top", "counter", "--gate", "--out", str(out), "--work-root", str(tmp_path / "w")])
    text = capsys.readouterr().out
    assert rc == 0 and out.read_text(encoding="utf-8").startswith("// Generated by")
    assert "[시도 1] 실패" in text and "[시도 2] 통과" in text and "게이트 통과" in text
    assert "unnamed block" in fake.calls[1].prompt


def test_gate_failure_returns_nonzero_after_max_attempts(rtl, tmp_path, monkeypatch, capsys):
    """--gate: 계속 실패하면 --max-attempts번에서 멈추고 종료 코드 1이다."""
    fake = install(monkeypatch, [fenced(GOOD_TB)] * 3, [XVLOG_FAIL] * 3)
    rc = gen_tb.main([str(rtl), "--top", "counter", "--gate", "--max-attempts", "2",
                      "--out", str(tmp_path / "tb.v"), "--work-root", str(tmp_path / "w")])
    assert rc == 1 and len(fake.calls) == 2 and "게이트 실패" in capsys.readouterr().out