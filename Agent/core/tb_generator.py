"""TB Generator 6-2: LLM을 한 번 불러 TB를 만들고 정적 검사까지 마친 결과를 돌려준다.

흐름: build_tb_prompt -> LLMClient.generate -> extract_verilog -> check_tb -> TBResult
컴파일(xvlog)과 실패 시 되먹임 재시도는 6-3 Compile Gate의 몫이다. 여기서는 한 번만 호출한다.

공개 API:
    generate_tb(summary, sources, client, spec_text=None, ...) -> TBResult
    render_tb_file(result) -> str     # 추적용 머리말 주석을 붙인 파일 내용
    save_tb(result, path) -> Path
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from pathlib import Path

from core.tb_check import Issue, check_tb, extract_verilog, has_errors
from core.tb_prompt import build_tb_prompt, tb_module_name
from llm.base import LLMRequest


@dataclass
class TBResult:
    top: str
    tb_name: str
    code: str                                   # 추출한 TB 코드 (없으면 "")
    issues: list[Issue]                         # 정적 검사 + 추출/잘림 문제
    raw_text: str                               # LLM 응답 원문 (디버깅용)
    model: str
    prompt_sha: str                             # system+prompt의 해시 12자리 (같은 입력인지 확인)
    input_tokens: int = 0
    output_tokens: int = 0
    cached: bool = False
    finish_reason: str | None = None
    extract_notes: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        """코드가 있고 error 수준 문제가 없음 (컴파일 가능 여부는 별개)."""
        return bool(self.code) and not has_errors(self.issues)


def _is_stop(finish_reason: str | None) -> bool:
    return finish_reason is None or str(finish_reason).upper().split(".")[-1] == "STOP"


def generate_tb(summary: dict, sources: dict[str, str], client, spec_text: str | None = None,
                model: str | None = None, temperature: float = 0.0,
                max_output_tokens: int = 8192) -> TBResult:
    """프롬프트를 만들고 LLM을 한 번 부른 뒤 TB를 검사한다. 프롬프트를 못 만들면 TBPromptError."""
    system, prompt = build_tb_prompt(summary, sources, spec_text)
    resp = client.generate(LLMRequest(prompt=prompt, system=system, model=model, temperature=temperature,
                                      max_output_tokens=max_output_tokens))
    code, notes = extract_verilog(resp.text)
    issues = check_tb(code, summary) if code else [Issue("error", "no_code", "응답에서 TB 코드를 찾지 못함")]
    if not _is_stop(resp.finish_reason):
        issues.insert(0, Issue("error", "truncated",
                               f"응답이 정상 종료되지 않음 (finish_reason={resp.finish_reason}) - 코드가 잘렸을 수 있음"))
    return TBResult(
        top=summary["top"], tb_name=tb_module_name(summary), code=code, issues=issues, raw_text=resp.text,
        model=resp.model, prompt_sha=hashlib.sha256((system + "\n" + prompt).encode()).hexdigest()[:12],
        input_tokens=resp.input_tokens, output_tokens=resp.output_tokens, cached=resp.cached,
        finish_reason=resp.finish_reason, extract_notes=notes)


def render_tb_file(result: TBResult) -> str:
    """생성 이력을 머리말 주석으로 남긴다 (어떤 모델, 어떤 프롬프트로 만든 TB인지 추적하기 위함)."""
    head = (f"// Generated by RTL Verification AI Agent (TB Generator)\n"
            f"// dut={result.top}  model={result.model}  prompt_sha={result.prompt_sha}\n")
    return head + result.code


def save_tb(result: TBResult, path: str | Path) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(render_tb_file(result), encoding="utf-8")
    return p
